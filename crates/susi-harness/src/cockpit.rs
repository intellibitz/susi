fn permille(numerator: u64, denominator: u64) -> u16 {
    if denominator == 0 {
        return 0;
    }
    let ratio = u128::from(numerator.min(denominator))
        .saturating_mul(1_000)
        .checked_div(u128::from(denominator))
        .unwrap_or(0);
    u16::try_from(ratio.min(1_000)).unwrap_or(1_000)
}

fn derive_state(view: &MissionView) -> String {
    match view.last_kind {
        Some(EventKind::MissionAborted) => return "aborted".into(),
        Some(EventKind::MissionPaused) => return "paused".into(),
        _ => {}
    }
    if view.planned > 0 && view.done >= view.planned {
        return "done".into();
    }
    if view.failed > 0 && view.last_kind == Some(EventKind::MissionFinished) {
        return "failed".into();
    }
    match view.last_kind {
        Some(
            EventKind::MissionStarted
            | EventKind::TaskDispatched
            | EventKind::TaskFinished
            | EventKind::ModelEscalated
            | EventKind::BudgetWarning,
        ) => "running".into(),
        Some(EventKind::MissionFinished) => "done".into(),
        Some(EventKind::MissionStuck) => "failed".into(),
        _ => "reported".into(),
    }
}

fn decisions(events: &[Event]) -> Vec<DecisionView> {
    let mut decisions = Vec::new();
    for event in events
        .iter()
        .filter(|event| event.kind == EventKind::DecisionRequested)
    {
        let resolved = events.iter().any(|later| {
            later.kind == EventKind::DecisionResolved
                && (later.summary.contains(&event.summary)
                    || event.summary.contains(&later.summary))
        });
        decisions.push(DecisionView {
            at_unix_ms: event.at_unix_ms,
            summary: event.summary.clone(),
            resolved,
        });
    }
    if decisions.len() > 10 {
        decisions = decisions.split_off(decisions.len() - 10);
    }
    decisions
}

#[derive(Debug, Clone, PartialEq, Eq, Default)]
struct Progress {
    status: String,
    reason: String,
}

fn read_progress(path: &Path) -> BTreeMap<String, Progress> {
    let Some(document) = read_json(path) else {
        return BTreeMap::new();
    };
    let mut progress = BTreeMap::new();
    if let Some(records) = document.get("records").and_then(Value::as_object) {
        for (key, record) in records {
            progress.insert(
                key.clone(),
                Progress {
                    status: record
                        .get("status")
                        .and_then(Value::as_str)
                        .unwrap_or_default()
                        .to_string(),
                    reason: record
                        .get("reason")
                        .and_then(Value::as_str)
                        .unwrap_or_default()
                        .to_string(),
                },
            );
        }
    }
    progress
}

fn read_json(path: &Path) -> Option<Value> {
    let text = std::fs::read_to_string(path).ok()?;
    serde_json::from_str(&text).ok()
}

/// What the admission policy sees for one operator write
/// (`POST /api/command`): the TCP peer, the request headers and the exact
/// buffered body, so a host can verify a bearer or a body-bound signature.
pub struct CommandAuthContext<'a> {
    /// Source address of the connection. When the server was not started with
    /// connect info it is the unspecified address, which is never loopback,
    /// so a loopback-only policy fails closed.
    pub peer: IpAddr,
    headers: &'a HeaderMap,
    /// The request body bytes the command handler will parse.
    pub body: &'a [u8],
}

impl CommandAuthContext<'_> {
    /// A request header as text, by case-insensitive name.
    pub fn header(&self, name: &str) -> Option<&str> {
        self.headers.get(name).and_then(|value| value.to_str().ok())
    }
}

/// Admission policy the host injects for `POST /api/command`; `true` admits
/// the write. The susi binary passes core's `NetGuard`.
pub type CommandAuthorizer = Arc<dyn for<'a> Fn(&CommandAuthContext<'a>) -> bool + Send + Sync>;

/// Largest command body the guard buffers; operator commands are tiny.
const MAX_COMMAND_BODY_BYTES: usize = 64 * 1024;

/// Build the harness API router (JSON and SSE only; no HTML route). Every
/// `POST /api/command` must pass `authorize` or is refused with `401`.
pub fn router(cockpit: Arc<Cockpit>, authorize: CommandAuthorizer) -> Router {
    let (on_status, on_events) = (Arc::clone(&cockpit), Arc::clone(&cockpit));
    Router::new()
        .route("/api/status", get(move |_| status(Arc::clone(&on_status))))
        .route("/api/events", get(move |_| events(Arc::clone(&on_events))))
        .route(
            "/api/command",
            post(move |request| command(Arc::clone(&cockpit), request))
                .guard(MAX_COMMAND_BODY_BYTES, command_guard(authorize)),
        )
        .route("/health", get(|_| health()))
}

/// Serve the harness API on an already-bound listener, with the peer address
/// available to `authorize`.
///
/// # Errors
///
/// Returns the listener's I/O error when the server stops.
pub async fn serve(
    listener: tokio::net::TcpListener,
    cockpit: Arc<Cockpit>,
    authorize: CommandAuthorizer,
) -> std::io::Result<()> {
    crate::http::serve(
        listener,
        router(cockpit, authorize),
        Peer::Pass,
        std::future::pending(),
    )
    .await
}

/// RFC 9110 15.5.2: a 401 carries a challenge naming the scheme to retry with.
fn unauthorized() -> Response {
    let mut response = Response::new(
        r#"{"error":"POST /api/command requires Authorization: Bearer <api token>"}"#,
    );
    *response.status_mut() = StatusCode::UNAUTHORIZED;
    response.headers_mut().insert(
        header::WWW_AUTHENTICATE,
        HeaderValue::from_static("Bearer realm=\"susi-harness\""),
    );
    response.headers_mut().insert(
        header::CONTENT_TYPE,
        HeaderValue::from_static("application/json"),
    );
    response
}

/// The admission check in front of `/api/command` (every method): the
/// server has read the body, at most [`MAX_COMMAND_BODY_BYTES`], and the
/// host's policy sees it with the peer and the headers.
fn command_guard(authorize: CommandAuthorizer) -> Guard {
    Arc::new(move |request: &Request| {
        let context = CommandAuthContext {
            peer: request
                .peer
                .map_or(IpAddr::V4(Ipv4Addr::UNSPECIFIED), |peer| peer.ip()),
            headers: &request.headers,
            body: &request.body,
        };
        (!(authorize)(&context)).then(unauthorized)
    })
}

